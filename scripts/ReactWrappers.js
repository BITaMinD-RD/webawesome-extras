// @ts-check

/**
 * Makes the React wrappers of the components from custom-elements.json, the way Web Awesome ships its own: one file per `wax-*` element, in `dist/react/`, that
 * exports a React component made with `createComponent` of `@lit/react`. The events `wax-select` become the props `onWaxSelect`; the attributes and properties
 * of the element are props as they are. The wrapper imports the element from `src/components/`, so a React application that has this package gets both.
 *
 * Each one has its `.d.ts` beside it, so that TypeScript and the editors know its props: the element is the one of `dist/types/`, and each event prop takes the class of its event
 * (`wax-query` is `WaxQueryEvent`, of `src/events/`; `wa-show` is the `WaShowEvent` of Web Awesome; any other, like `change`, a plain `Event`).
 *
 * Pure: it gives back the files (name and text) and does not write them; `scripts/react.mjs` writes them and a test compares them with what is committed.
 */

/** @param {string} tagName `wax-item-list` @returns {string} `WaxItemList` */
export const classNameOf = tagName => tagName.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('');

/** @param {string} eventName `wax-select` @returns {string} `onWaxSelect` */
export const propOfEvent = eventName => `on${classNameOf(eventName)}`;

/**
 * The class of an event and where it comes from, by its name: the `wax-*` ones are in `src/events/` (their declarations in `dist/types/events/`), the `wa-*` ones in `dist/events/` of Web Awesome.
 *
 * @param {string} eventName `wax-site-click`
 * @returns {{name: string, from: string} | null} `{ name: 'WaxSiteClickEvent', from: '../types/events/events.js' }`; null for an event of the DOM (`change`)
 */
export function eventClassOf(eventName) {
  if (eventName.startsWith('wax-')) return { name: `${classNameOf(eventName)}Event`, from: '../types/events/events.js' };
  if (eventName.startsWith('wa-')) return { name: `${classNameOf(eventName)}Event`, from: `@awesome.me/webawesome/dist/events/${eventName.slice(3)}.js` };
  return null;
}

/**
 * @typedef {{kind: string, name: string, tagName?: string, customElement?: boolean, events?: {name: string}[]}} Declaration
 * @typedef {{path: string, declarations?: Declaration[]}} Module
 */

/**
 * @param {{modules: Module[]}} manifest The parsed custom-elements.json
 * @returns {Map<string, string>} The text of each file, by its name inside `dist/react/` (`wax-item-list.js` and `wax-item-list.d.ts`, and `index.js` and `index.d.ts`, which export them all)
 */
export function reactWrappers(manifest) {
  /** @type {Map<string, string>} */
  const files = new Map();
  const exported = [];
  for (const module of manifest.modules) {
    for (const declaration of module.declarations ?? []) {
      if (declaration.kind !== 'class' || !declaration.customElement || !declaration.tagName) continue;
      const events = (declaration.events ?? []).map(event => `    ${propOfEvent(event.name)}: '${event.name}',`);
      files.set(`${declaration.tagName}.js`, [
        `// Generated by scripts/react.mjs from custom-elements.json: do not edit by hand`,
        `import * as React from 'react';`,
        `import { createComponent } from '@lit/react';`,
        `import { ${declaration.name} as Element } from '../../${module.path}';`,
        ``,
        `export const ${declaration.name} = createComponent({`,
        `  tagName: '${declaration.tagName}',`,
        `  elementClass: Element,`,
        `  react: React,`,
        `  events: {`,
        ...events,
        `  },`,
        `});`,
        ``
      ].join('\n'));
      const classes = (declaration.events ?? []).map(event => eventClassOf(event.name)).filter(found => found !== null);
      const imports = [...new Set(classes.map(found => found.from))].map(from => `import type { ${[...new Set(classes.filter(found => found.from === from).map(found => found.name))].sort().join(', ')} } from '${from}';`);
      const props = (declaration.events ?? []).map(event => `  ${propOfEvent(event.name)}: EventName<${eventClassOf(event.name)?.name ?? 'Event'}>;`);
      files.set(`${declaration.tagName}.d.ts`, [
        `// Generated by scripts/react.mjs from custom-elements.json: do not edit by hand`,
        `import type { EventName, ReactWebComponent } from '@lit/react';`,
        `import type { ${declaration.name} as Element } from '../types/${module.path.replace(/^src\//, '')}';`,
        ...imports,
        ``,
        `export declare const ${declaration.name}: ReactWebComponent<Element, {`,
        ...props,
        `}>;`,
        ``
      ].join('\n'));
      exported.push(declaration.tagName);
    }
  }
  const index = [`// Generated by scripts/react.mjs from custom-elements.json: do not edit by hand`, ...exported.sort().map(tag => `export * from './${tag}.js';`), ``].join('\n');
  files.set('index.js', index);
  files.set('index.d.ts', index);
  return files;
}
