// @ts-check

/**
 * Makes the React wrappers of the components from custom-elements.json, the way Web Awesome ships its own: one file per `wax-*` element, in `dist/react/`, that
 * exports a React component made with `createComponent` of `@lit/react`. The events `wax-select` become the props `onWaxSelect`; the attributes and properties
 * of the element are props as they are. The wrapper imports the element from `src/components/`, so a React application that has this package gets both.
 *
 * Pure: it gives back the files (name and text) and does not write them; `scripts/react.mjs` writes them and a test compares them with what is committed.
 */

/** @param {string} tagName `wax-item-list` @returns {string} `WaxItemList` */
export const classNameOf = tagName => tagName.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('');

/** @param {string} eventName `wax-select` @returns {string} `onWaxSelect` */
export const propOfEvent = eventName => `on${classNameOf(eventName)}`;

/**
 * @typedef {{kind: string, name: string, tagName?: string, customElement?: boolean, events?: {name: string}[]}} Declaration
 * @typedef {{path: string, declarations?: Declaration[]}} Module
 */

/**
 * @param {{modules: Module[]}} manifest The parsed custom-elements.json
 * @returns {Map<string, string>} The text of each file, by its name inside `dist/react/` (`wax-item-list.js`, and `index.js`, which exports them all)
 */
export function reactWrappers(manifest) {
  /** @type {Map<string, string>} */
  const files = new Map();
  const exported = [];
  for (const module of manifest.modules) {
    for (const declaration of module.declarations ?? []) {
      if (declaration.kind !== 'class' || !declaration.customElement || !declaration.tagName) continue;
      const events = (declaration.events ?? []).map(event => `    ${propOfEvent(event.name)}: '${event.name}',`);
      files.set(`${declaration.tagName}.js`, [
        `// Generated by scripts/react.mjs from custom-elements.json: do not edit by hand`,
        `import * as React from 'react';`,
        `import { createComponent } from '@lit/react';`,
        `import { ${declaration.name} as Element } from '../../${module.path}';`,
        ``,
        `export const ${declaration.name} = createComponent({`,
        `  tagName: '${declaration.tagName}',`,
        `  elementClass: Element,`,
        `  react: React,`,
        `  events: {`,
        ...events,
        `  },`,
        `});`,
        ``
      ].join('\n'));
      exported.push(declaration.tagName);
    }
  }
  files.set('index.js', [`// Generated by scripts/react.mjs from custom-elements.json: do not edit by hand`, ...exported.sort().map(tag => `export * from './${tag}.js';`), ``].join('\n'));
  return files;
}
